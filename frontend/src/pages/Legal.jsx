export default function Legal({ initialDoc = "privacy" }) {
  const [activeKey, setActiveKey] = useState(
    DOCUMENTS.some((d) => d.key === initialDoc) ? initialDoc : DOCUMENTS[0].key
  );
  const doc = useMemo(() => DOCUMENTS.find((d) => d.key === activeKey) || DOCUMENTS[0], [activeKey]);

  const scrollTo = (id) => {
    const el = document.getElementById(id);
    if (el) el.scrollIntoView({ behavior: "smooth", block: "start" });
  };

  return (
    <section className="legal-page legal-hub">
      <h1>Правовые документы</h1>
      <p className="legal-meta">
        Оператор персональных данных — организатор конференции · Редакция актуальна на дату
        обращения · версия 2.1
      </p>

      <div className="legal-tabs" role="tablist">
        {DOCUMENTS.map((d) => (
          <button
            key={d.key}
            type="button"
            role="tab"
            aria-selected={d.key === activeKey}
            className={`legal-tab ${d.key === activeKey ? "active" : ""}`}
            onClick={() => setActiveKey(d.key)}
          >
            {d.tab}
          </button>
        ))}
      </div>

      <div className="legal-layout">
        <aside className="legal-toc" aria-label="Содержание документа">
          <div className="legal-toc-title">Содержание</div>
          <nav>
            {doc.sections.map((s) => (
              <button key={s.id} type="button" className="legal-toc-link" onClick={() => scrollTo(s.id)}>
                {s.heading}
              </button>
            ))}
          </nav>
        </aside>

        <div className="legal-content">
          <h2 className="legal-doc-title">{doc.title}</h2>
          <div className="legal-text">
            {doc.sections.map((s) => (
              <div key={s.id} id={s.id} className="legal-section">
                <h3>{s.heading}</h3>
                <p>{s.body}</p>
              </div>
            ))}
          </div>
          <div className="legal-divider" />
          <div className="legal-actions">
            <button type="button" className="legal-action" onClick={() => window.print()}>
              <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" aria-hidden="true">
                <path d="M12 3v12m0 0 4-4m-4 4-4-4" />
                <path d="M5 21h14" />
              </svg>
              Скачать PDF
            </button>
            <Link to="/register" className="legal-action">
              <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" aria-hidden="true">
                <path d="M19 12H5m0 0 6-6m-6 6 6 6" />
              </svg>
              Назад к регистрации
            </Link>
          </div>
        </div>
      </div>
    </section>
  );
}
